std::vector<uint8_t> serialize(const ConnectivitySnapshot& snapshot) {
  flatbuffers::FlatBufferBuilder builder;

  std::vector<flatbuffers::Offset<fbs::NetEntry>> nets;
  snapshot.table<Net>().for_each([&](core::EntityId id, const Net& net) {
    nets.push_back(fbs::CreateNetEntry(builder, id.value(), write_net(builder, net)));
  });

  std::vector<flatbuffers::Offset<fbs::PinEntry>> pins;
  snapshot.table<Pin>().for_each([&](core::EntityId id, const Pin& pin) {
    pins.push_back(fbs::CreatePinEntry(builder, id.value(), write_pin(builder, pin)));
  });

  std::vector<flatbuffers::Offset<fbs::DifferentialPairEntry>> diff_pairs;
  snapshot.table<DifferentialPair>().for_each([&](core::EntityId id, const DifferentialPair& pair) {
    diff_pairs.push_back(
        fbs::CreateDifferentialPairEntry(builder, id.value(), write_diff_pair(builder, pair)));
  });

  std::vector<flatbuffers::Offset<fbs::BusEntry>> buses;
  snapshot.table<Bus>().for_each([&](core::EntityId id, const Bus& bus) {
    buses.push_back(fbs::CreateBusEntry(builder, id.value(), write_bus(builder, bus)));
  });

  const flatbuffers::Offset<fbs::ConnectivitySnapshot> root =
      fbs::CreateConnectivitySnapshotDirect(builder, &nets, &pins, &diff_pairs, &buses);
  builder.Finish(root);

  const uint8_t* buffer_ptr = builder.GetBufferPointer();
  // GetBufferPointer()/GetSize() are a guaranteed-consistent pair from the
  // FlatBufferBuilder's own contract.
  // NOLINTNEXTLINE(cppcoreguidelines-pro-bounds-pointer-arithmetic)
  return {buffer_ptr, buffer_ptr + builder.GetSize()};
}

ConnectivityWorkspace deserialize_connectivity(std::span<const uint8_t> buffer) {
  // NOLINTNEXTLINE(misc-include-cleaner)
  flatbuffers::Verifier verifier(buffer.data(), buffer.size());
  if (!fbs::VerifyConnectivitySnapshotBuffer(verifier)) {
    throw FormatError("corrupt or malformed connectivity snapshot buffer");
  }

  const fbs::ConnectivitySnapshot* snapshot = fbs::GetConnectivitySnapshot(buffer.data());
  ConnectivityWorkspace workspace;

  if (const auto* nets = snapshot->nets()) {
    for (const fbs::NetEntry* entry : *nets) {
      workspace.insert_with_id(read_net(entry->value()), core::EntityId{entry->id()});
    }
  }
  if (const auto* pins = snapshot->pins()) {
    for (const fbs::PinEntry* entry : *pins) {
      workspace.insert_with_id(read_pin(entry->value()), core::EntityId{entry->id()});
    }
  }
  if (const auto* diff_pairs = snapshot->diff_pairs()) {
    for (const fbs::DifferentialPairEntry* entry : *diff_pairs) {
      workspace.insert_with_id(read_diff_pair(entry->value()), core::EntityId{entry->id()});
    }
  }
  if (const auto* buses = snapshot->buses()) {
    for (const fbs::BusEntry* entry : *buses) {
      workspace.insert_with_id(read_bus(entry->value()), core::EntityId{entry->id()});
    }
  }

  return workspace;
}

