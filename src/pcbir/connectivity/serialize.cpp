// NOLINTNEXTLINE(misc-include-cleaner)
flatbuffers::Offset<fbs::Net> write_net(flatbuffers::FlatBufferBuilder& builder, const Net& net) {
  return fbs::CreateNetDirect(builder, net.name.c_str());
}

Net read_net(const fbs::Net* net) {
  return Net{.name = net->name() != nullptr ? net->name()->str() : std::string()};
}

flatbuffers::Offset<fbs::Pin> write_pin(flatbuffers::FlatBufferBuilder& builder, const Pin& pin) {
  return fbs::CreatePin(builder, pin.pad.value(), pin.net.value());
}

Pin read_pin(const fbs::Pin* pin) {
  return Pin{.pad = core::EntityId{pin->pad()}, .net = core::EntityId{pin->net()}};
}

flatbuffers::Offset<fbs::DifferentialPair> write_diff_pair(flatbuffers::FlatBufferBuilder& builder,
                                                           const DifferentialPair& pair) {
  return fbs::CreateDifferentialPair(builder, pair.positive_net.value(), pair.negative_net.value());
}

DifferentialPair read_diff_pair(const fbs::DifferentialPair* pair) {
  return DifferentialPair{.positive_net = core::EntityId{pair->positive_net()},
                          .negative_net = core::EntityId{pair->negative_net()}};
}

flatbuffers::Offset<fbs::Bus> write_bus(flatbuffers::FlatBufferBuilder& builder, const Bus& bus) {
  std::vector<uint64_t> members;
  members.reserve(bus.members.size());
  for (const core::EntityId& member : bus.members) {
    members.push_back(member.value());
  }
  return fbs::CreateBusDirect(builder, bus.name.c_str(), &members);
}

Bus read_bus(const fbs::Bus* bus) {
  Bus result{.name = bus->name() != nullptr ? bus->name()->str() : std::string(), .members = {}};
  if (const auto* members = bus->members()) {
    result.members.reserve(members->size());
    for (const uint64_t member : *members) {
      result.members.emplace_back(member);
    }
  }
  return result;
}

