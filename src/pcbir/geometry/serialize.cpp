// -- Point --------------------------------------------------------------

fbs::Point write_point(const Point& point) {
  return {point.x, point.y};
}

Point read_point(const fbs::Point* point) {
  return Point{.x = point->x(), .y = point->y()};
}

// -- Segment / Arc / Span (union) ----------------------------------------

// NOLINTNEXTLINE(misc-include-cleaner)
flatbuffers::Offset<fbs::Segment> write_segment(flatbuffers::FlatBufferBuilder& builder,
                                                const Segment& segment) {
  const fbs::Point start = write_point(segment.start);
  const fbs::Point finish = write_point(segment.end);
  return fbs::CreateSegment(builder, &start, &finish);
}

Segment read_segment(const fbs::Segment* segment) {
  return Segment{.start = read_point(segment->start()), .end = read_point(segment->finish())};
}

flatbuffers::Offset<fbs::Arc> write_arc(flatbuffers::FlatBufferBuilder& builder, const Arc& arc) {
  const fbs::Point start = write_point(arc.start);
  const fbs::Point finish = write_point(arc.end);
  const fbs::Point center = write_point(arc.center);
  const auto direction = arc.direction == ArcDirection::Clockwise
                             ? fbs::ArcDirection_Clockwise
                             : fbs::ArcDirection_CounterClockwise;
  return fbs::CreateArc(builder, &start, &finish, &center, direction);
}

Arc read_arc(const fbs::Arc* arc) {
  const ArcDirection direction = arc->direction() == fbs::ArcDirection_Clockwise
                                     ? ArcDirection::Clockwise
                                     : ArcDirection::CounterClockwise;
  return Arc{.start = read_point(arc->start()),
             .end = read_point(arc->finish()),
             .center = read_point(arc->center()),
             .direction = direction};
}

struct WrittenSpan {
  fbs::Span type = fbs::Span_NONE;
  flatbuffers::Offset<void> offset;
};

WrittenSpan write_span(flatbuffers::FlatBufferBuilder& builder, const Span& span) {
  if (const auto* segment = std::get_if<Segment>(&span)) {
    return WrittenSpan{.type = fbs::Span_Segment,
                       .offset = write_segment(builder, *segment).Union()};
  }
  return WrittenSpan{.type = fbs::Span_Arc,
                     .offset = write_arc(builder, std::get<Arc>(span)).Union()};
}

Span read_span(fbs::Span type, const void* geometry) {
  if (type == fbs::Span_Arc) {
    return Span{read_arc(static_cast<const fbs::Arc*>(geometry))};
  }
  if (type == fbs::Span_Segment) {
    return Span{read_segment(static_cast<const fbs::Segment*>(geometry))};
  }
  // Span_NONE never occurs for a spans_type entry the writer above
  // produces; FlatBuffers' union verification does not reject NONE paired
  // with a present value offset (docs/format-spec.md -- Serialization
  // fuzz target), so a NONE type here means the buffer is malformed --
  // reject it rather than reinterpreting an unrelated payload as a
  // Segment.
  throw FormatError("corrupt or malformed geometry snapshot buffer: span has no type");
}

// -- WidthSpan / Path -----------------------------------------------------

flatbuffers::Offset<fbs::WidthSpan> write_width_span(flatbuffers::FlatBufferBuilder& builder,
                                                     const WidthSpan& span) {
  const WrittenSpan written = write_span(builder, span.geometry);
  return fbs::CreateWidthSpan(builder, written.type, written.offset, span.width_nm);
}

WidthSpan read_width_span(const fbs::WidthSpan* span) {
  return WidthSpan{.geometry = read_span(span->geometry_type(), span->geometry()),
                   .width_nm = span->width_nm()};
}

flatbuffers::Offset<fbs::Path> write_path(flatbuffers::FlatBufferBuilder& builder,
                                          const Path& path) {
  std::vector<flatbuffers::Offset<fbs::WidthSpan>> spans;
  spans.reserve(path.spans.size());
  for (const WidthSpan& span : path.spans) {
    spans.push_back(write_width_span(builder, span));
  }
  return fbs::CreatePathDirect(builder, &spans);
}

Path read_path(const fbs::Path* path) {
  Path result;
  if (const auto* spans = path->spans()) {
    result.spans.reserve(spans->size());
    for (const fbs::WidthSpan* span : *spans) {
      result.spans.push_back(read_width_span(span));
    }
  }
  return result;
}

// -- Contour / Polygon ----------------------------------------------------

flatbuffers::Offset<fbs::Contour> write_contour(flatbuffers::FlatBufferBuilder& builder,
                                                const Contour& contour) {
  std::vector<uint8_t> types;
  std::vector<flatbuffers::Offset<void>> offsets;
  types.reserve(contour.spans.size());
  offsets.reserve(contour.spans.size());
  for (const Span& span : contour.spans) {
    const WrittenSpan written = write_span(builder, span);
    types.push_back(static_cast<uint8_t>(written.type));
    offsets.push_back(written.offset);
  }
  return fbs::CreateContourDirect(builder, &types, &offsets);
}

Contour read_contour(const fbs::Contour* contour) {
  Contour result;
  const auto* types = contour->spans_type();
  const auto* spans = contour->spans();
  if (types != nullptr && spans != nullptr) {
    result.spans.reserve(spans->size());
    // NOLINTNEXTLINE(misc-include-cleaner)
    for (flatbuffers::uoffset_t i = 0; i < spans->size(); ++i) {
      // NOLINTNEXTLINE(cppcoreguidelines-pro-bounds-avoid-unchecked-container-access)
      result.spans.push_back(read_span(static_cast<fbs::Span>(types->Get(i)), spans->Get(i)));
    }
  }
  return result;
}

flatbuffers::Offset<fbs::Polygon> write_polygon(flatbuffers::FlatBufferBuilder& builder,
                                                const Polygon& polygon) {
  const flatbuffers::Offset<fbs::Contour> outline = write_contour(builder, polygon.outline);
  std::vector<flatbuffers::Offset<fbs::Contour>> holes;
  holes.reserve(polygon.holes.size());
  for (const Contour& hole : polygon.holes) {
    holes.push_back(write_contour(builder, hole));
  }
  return fbs::CreatePolygonDirect(builder, outline, &holes);
}

Polygon read_polygon(const fbs::Polygon* polygon) {
  Polygon result;
  result.outline = read_contour(polygon->outline());
  if (const auto* holes = polygon->holes()) {
    result.holes.reserve(holes->size());
    for (const fbs::Contour* hole : *holes) {
      result.holes.push_back(read_contour(hole));
    }
  }
  return result;
}

