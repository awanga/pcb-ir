std::vector<uint8_t> serialize(const GeometrySnapshot& snapshot) {
  flatbuffers::FlatBufferBuilder builder;

  std::vector<flatbuffers::Offset<fbs::PadEntry>> pads;
  snapshot.table<Pad>().for_each([&](core::EntityId id, const Pad& pad) {
    pads.push_back(fbs::CreatePadEntry(builder, id.value(), write_pad(builder, pad)));
  });

  std::vector<flatbuffers::Offset<fbs::ViaEntry>> vias;
  snapshot.table<Via>().for_each([&](core::EntityId id, const Via& via) {
    vias.push_back(fbs::CreateViaEntry(builder, id.value(), write_via(builder, via)));
  });

  std::vector<flatbuffers::Offset<fbs::TrackEntry>> tracks;
  snapshot.table<Track>().for_each([&](core::EntityId id, const Track& track) {
    tracks.push_back(fbs::CreateTrackEntry(builder, id.value(), write_track(builder, track)));
  });

  std::vector<flatbuffers::Offset<fbs::CopperPourEntry>> copper_pours;
  snapshot.table<CopperPour>().for_each([&](core::EntityId id, const CopperPour& pour) {
    copper_pours.push_back(
        fbs::CreateCopperPourEntry(builder, id.value(), write_copper_pour(builder, pour)));
  });

  std::vector<flatbuffers::Offset<fbs::KeepoutEntry>> keepouts;
  snapshot.table<Keepout>().for_each([&](core::EntityId id, const Keepout& keepout) {
    keepouts.push_back(
        fbs::CreateKeepoutEntry(builder, id.value(), write_keepout(builder, keepout)));
  });

  std::vector<flatbuffers::Offset<fbs::DrillHitEntry>> drill_hits;
  snapshot.table<DrillHit>().for_each([&](core::EntityId id, const DrillHit& hit) {
    drill_hits.push_back(
        fbs::CreateDrillHitEntry(builder, id.value(), write_drill_hit(builder, hit)));
  });

  std::vector<flatbuffers::Offset<fbs::MaskOpeningEntry>> mask_openings;
  snapshot.table<MaskOpening>().for_each([&](core::EntityId id, const MaskOpening& opening) {
    mask_openings.push_back(
        fbs::CreateMaskOpeningEntry(builder, id.value(), write_mask_opening(builder, opening)));
  });

  std::vector<flatbuffers::Offset<fbs::SilkscreenGraphicEntry>> silkscreen_graphics;
  snapshot.table<SilkscreenGraphic>().for_each(
      [&](core::EntityId id, const SilkscreenGraphic& graphic) {
        silkscreen_graphics.push_back(fbs::CreateSilkscreenGraphicEntry(
            builder, id.value(), write_silkscreen_graphic(builder, graphic)));
      });

  std::vector<flatbuffers::Offset<fbs::FootprintEntry>> footprints;
  snapshot.table<Footprint>().for_each([&](core::EntityId id, const Footprint& footprint) {
    footprints.push_back(
        fbs::CreateFootprintEntry(builder, id.value(), write_footprint(builder, footprint)));
  });

  std::vector<flatbuffers::Offset<fbs::BoardOutlineEntry>> board_outlines;
  snapshot.table<BoardOutline>().for_each([&](core::EntityId id, const BoardOutline& outline) {
    board_outlines.push_back(
        fbs::CreateBoardOutlineEntry(builder, id.value(), write_board_outline(builder, outline)));
  });

  const flatbuffers::Offset<fbs::GeometrySnapshot> root =
      fbs::CreateGeometrySnapshotDirect(builder,
                                        &pads,
                                        &vias,
                                        &tracks,
                                        &copper_pours,
                                        &keepouts,
                                        &drill_hits,
                                        &mask_openings,
                                        &silkscreen_graphics,
                                        &footprints,
                                        &board_outlines);
  builder.Finish(root);

  const uint8_t* buffer_ptr = builder.GetBufferPointer();
  // GetBufferPointer()/GetSize() are a guaranteed-consistent pair from the
  // FlatBufferBuilder's own contract.
  // NOLINTNEXTLINE(cppcoreguidelines-pro-bounds-pointer-arithmetic)
  return {buffer_ptr, buffer_ptr + builder.GetSize()};
}

GeometryWorkspace deserialize_geometry(std::span<const uint8_t> buffer) {
  // NOLINTNEXTLINE(misc-include-cleaner)
  flatbuffers::Verifier verifier(buffer.data(), buffer.size());
  if (!fbs::VerifyGeometrySnapshotBuffer(verifier)) {
    throw FormatError("corrupt or malformed geometry snapshot buffer");
  }

  const fbs::GeometrySnapshot* snapshot = fbs::GetGeometrySnapshot(buffer.data());
  GeometryWorkspace workspace;

  insert_entries(workspace, snapshot->pads(), read_pad);
  insert_entries(workspace, snapshot->vias(), read_via);
  insert_entries(workspace, snapshot->tracks(), read_track);
  insert_entries(workspace, snapshot->copper_pours(), read_copper_pour);
  insert_entries(workspace, snapshot->keepouts(), read_keepout);
  insert_entries(workspace, snapshot->drill_hits(), read_drill_hit);
  insert_entries(workspace, snapshot->mask_openings(), read_mask_opening);
  insert_entries(workspace, snapshot->silkscreen_graphics(), read_silkscreen_graphic);
  insert_entries(workspace, snapshot->footprints(), read_footprint);
  insert_entries(workspace, snapshot->board_outlines(), read_board_outline);

  return workspace;
}

