// NOLINTNEXTLINE(misc-include-cleaner)
flatbuffers::Offset<fbs::Material> write_material(flatbuffers::FlatBufferBuilder& builder,
                                                  const Material& material) {
  return fbs::CreateMaterialDirect(
      builder, material.name.c_str(), material.dielectric_constant_e6, material.loss_tangent_e6);
}

Material read_material(const fbs::Material* material) {
  return Material{.name = material->name() != nullptr ? material->name()->str() : std::string(),
                  .dielectric_constant_e6 = material->dielectric_constant_e6(),
                  .loss_tangent_e6 = material->loss_tangent_e6()};
}

fbs::LayerKind write_layer_kind(LayerKind kind) {
  return kind == LayerKind::Copper ? fbs::LayerKind_Copper : fbs::LayerKind_Dielectric;
}

LayerKind read_layer_kind(fbs::LayerKind kind) {
  return kind == fbs::LayerKind_Copper ? LayerKind::Copper : LayerKind::Dielectric;
}

flatbuffers::Offset<fbs::Layer> write_layer(flatbuffers::FlatBufferBuilder& builder,
                                            const Layer& layer) {
  return fbs::CreateLayerDirect(builder,
                                layer.name.c_str(),
                                write_layer_kind(layer.kind),
                                layer.thickness_nm,
                                layer.roughness_nm,
                                layer.material.value());
}

Layer read_layer(const fbs::Layer* layer) {
  return Layer{.name = layer->name() != nullptr ? layer->name()->str() : std::string(),
               .kind = read_layer_kind(layer->kind()),
               .thickness_nm = layer->thickness_nm(),
               .roughness_nm = layer->roughness_nm(),
               .material = core::EntityId{layer->material()}};
}

flatbuffers::Offset<fbs::LayerStack> write_layer_stack(flatbuffers::FlatBufferBuilder& builder,
                                                       const LayerStack& stack) {
  std::vector<uint64_t> layers;
  layers.reserve(stack.layers.size());
  for (const core::EntityId& layer : stack.layers) {
    layers.push_back(layer.value());
  }
  return fbs::CreateLayerStackDirect(builder, stack.name.c_str(), &layers);
}

LayerStack read_layer_stack(const fbs::LayerStack* stack) {
  LayerStack result{.name = stack->name() != nullptr ? stack->name()->str() : std::string(),
                    .layers = {}};
  if (const auto* layers = stack->layers()) {
    result.layers.reserve(layers->size());
    for (const uint64_t layer : *layers) {
      result.layers.emplace_back(layer);
    }
  }
  return result;
}

flatbuffers::Offset<fbs::ImpedanceProfile>
write_impedance_profile(flatbuffers::FlatBufferBuilder& builder, const ImpedanceProfile& profile) {
  return fbs::CreateImpedanceProfileDirect(
      builder, profile.class_name.c_str(), profile.target_ohm_e6, profile.actual_ohm_e6);
}

ImpedanceProfile read_impedance_profile(const fbs::ImpedanceProfile* profile) {
  return ImpedanceProfile{
      .class_name = profile->class_name() != nullptr ? profile->class_name()->str() : std::string(),
      .target_ohm_e6 = profile->target_ohm_e6(),
      .actual_ohm_e6 = profile->actual_ohm_e6()};
}

