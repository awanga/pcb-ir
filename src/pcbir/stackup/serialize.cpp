std::vector<uint8_t> serialize(const StackupSnapshot& snapshot) {
  flatbuffers::FlatBufferBuilder builder;

  std::vector<flatbuffers::Offset<fbs::MaterialEntry>> materials;
  snapshot.table<Material>().for_each([&](core::EntityId id, const Material& material) {
    materials.push_back(
        fbs::CreateMaterialEntry(builder, id.value(), write_material(builder, material)));
  });

  std::vector<flatbuffers::Offset<fbs::LayerEntry>> layers;
  snapshot.table<Layer>().for_each([&](core::EntityId id, const Layer& layer) {
    layers.push_back(fbs::CreateLayerEntry(builder, id.value(), write_layer(builder, layer)));
  });

  std::vector<flatbuffers::Offset<fbs::LayerStackEntry>> layer_stacks;
  snapshot.table<LayerStack>().for_each([&](core::EntityId id, const LayerStack& stack) {
    layer_stacks.push_back(
        fbs::CreateLayerStackEntry(builder, id.value(), write_layer_stack(builder, stack)));
  });

  std::vector<flatbuffers::Offset<fbs::ImpedanceProfileEntry>> impedance_profiles;
  snapshot.table<ImpedanceProfile>().for_each(
      [&](core::EntityId id, const ImpedanceProfile& profile) {
        impedance_profiles.push_back(fbs::CreateImpedanceProfileEntry(
            builder, id.value(), write_impedance_profile(builder, profile)));
      });

  const flatbuffers::Offset<fbs::StackupSnapshot> root = fbs::CreateStackupSnapshotDirect(
      builder, &materials, &layers, &layer_stacks, &impedance_profiles);
  builder.Finish(root);

  const uint8_t* buffer_ptr = builder.GetBufferPointer();
  // GetBufferPointer()/GetSize() are a guaranteed-consistent pair from the
  // FlatBufferBuilder's own contract.
  // NOLINTNEXTLINE(cppcoreguidelines-pro-bounds-pointer-arithmetic)
  return {buffer_ptr, buffer_ptr + builder.GetSize()};
}

StackupWorkspace deserialize_stackup(std::span<const uint8_t> buffer) {
  const fbs::StackupSnapshot* snapshot = fbs::GetStackupSnapshot(buffer.data());
  StackupWorkspace workspace;

  if (const auto* materials = snapshot->materials()) {
    for (const fbs::MaterialEntry* entry : *materials) {
      workspace.insert_with_id(read_material(entry->value()), core::EntityId{entry->id()});
    }
  }
  if (const auto* layers = snapshot->layers()) {
    for (const fbs::LayerEntry* entry : *layers) {
      workspace.insert_with_id(read_layer(entry->value()), core::EntityId{entry->id()});
    }
  }
  if (const auto* layer_stacks = snapshot->layer_stacks()) {
    for (const fbs::LayerStackEntry* entry : *layer_stacks) {
      workspace.insert_with_id(read_layer_stack(entry->value()), core::EntityId{entry->id()});
    }
  }
  if (const auto* impedance_profiles = snapshot->impedance_profiles()) {
    for (const fbs::ImpedanceProfileEntry* entry : *impedance_profiles) {
      workspace.insert_with_id(read_impedance_profile(entry->value()), core::EntityId{entry->id()});
    }
  }

  return workspace;
}

