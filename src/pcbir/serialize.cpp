// -- FormatVersion / EntityDomain ----------------------------------------

fbs::FormatVersion write_format_version(const FormatVersion& version) {
  return {version.major, version.minor};
}

FormatVersion read_format_version(const fbs::FormatVersion* version) {
  return FormatVersion{.major = version->major(), .minor = version->minor()};
}

fbs::EntityDomain write_entity_domain(EntityDomain domain) {
  if (domain == EntityDomain::Geometry) {
    return fbs::EntityDomain_Geometry;
  }
  if (domain == EntityDomain::Connectivity) {
    return fbs::EntityDomain_Connectivity;
  }
  return fbs::EntityDomain_Stackup;
}

EntityDomain read_entity_domain(fbs::EntityDomain domain) {
  if (domain == fbs::EntityDomain_Geometry) {
    return EntityDomain::Geometry;
  }
  if (domain == fbs::EntityDomain_Connectivity) {
    return EntityDomain::Connectivity;
  }
  return EntityDomain::Stackup;
}

// -- Extension / PassthroughBlob ------------------------------------------

// NOLINTNEXTLINE(misc-include-cleaner)
flatbuffers::Offset<fbs::ExtensionEntry> write_extension(flatbuffers::FlatBufferBuilder& builder,
                                                         const Extension& extension) {
  return fbs::CreateExtensionEntryDirect(builder,
                                         write_entity_domain(extension.domain),
                                         extension.entity_id.value(),
                                         extension.ext_namespace.c_str(),
                                         extension.name.c_str(),
                                         extension.version,
                                         &extension.payload);
}

Extension read_extension(const fbs::ExtensionEntry* entry) {
  return Extension{
      .domain = read_entity_domain(entry->domain()),
      .entity_id = core::EntityId{entry->entity_id()},
      .ext_namespace =
          entry->ext_namespace() != nullptr ? entry->ext_namespace()->str() : std::string(),
      .name = entry->name() != nullptr ? entry->name()->str() : std::string(),
      .version = entry->version(),
      .payload = entry->payload() != nullptr
                     ? std::vector<uint8_t>(entry->payload()->begin(), entry->payload()->end())
                     : std::vector<uint8_t>()};
}

flatbuffers::Offset<fbs::PassthroughBlobEntry>
write_passthrough_blob(flatbuffers::FlatBufferBuilder& builder, const PassthroughBlob& blob) {
  return fbs::CreatePassthroughBlobEntryDirect(builder,
                                               write_entity_domain(blob.domain),
                                               blob.entity_id.value(),
                                               blob.source_format.c_str(),
                                               &blob.data);
}

PassthroughBlob read_passthrough_blob(const fbs::PassthroughBlobEntry* entry) {
  return PassthroughBlob{
      .domain = read_entity_domain(entry->domain()),
      .entity_id = core::EntityId{entry->entity_id()},
      .source_format =
          entry->source_format() != nullptr ? entry->source_format()->str() : std::string(),
      .data = entry->data() != nullptr
                  ? std::vector<uint8_t>(entry->data()->begin(), entry->data()->end())
                  : std::vector<uint8_t>()};
}

