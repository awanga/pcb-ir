std::vector<uint8_t> serialize(const BoardSnapshot& board) {
  flatbuffers::FlatBufferBuilder builder;

  // Each layer keeps serializing itself exactly as it already did in its
  // own phase (Phases 2-4); composing a board never re-derives a layer's
  // bytes, it only embeds them.
  const std::vector<uint8_t> geometry_bytes = geometry::serialize(board.geometry);
  const std::vector<uint8_t> connectivity_bytes = connectivity::serialize(board.connectivity);
  const std::vector<uint8_t> stackup_bytes = stackup::serialize(board.stackup);

  std::vector<flatbuffers::Offset<fbs::ExtensionEntry>> extensions;
  extensions.reserve(board.extensions.size());
  for (const Extension& extension : board.extensions) {
    extensions.push_back(write_extension(builder, extension));
  }

  std::vector<flatbuffers::Offset<fbs::PassthroughBlobEntry>> passthrough_blobs;
  passthrough_blobs.reserve(board.passthrough_blobs.size());
  for (const PassthroughBlob& blob : board.passthrough_blobs) {
    passthrough_blobs.push_back(write_passthrough_blob(builder, blob));
  }

  const fbs::FormatVersion format_version = write_format_version(board.format_version);
  const flatbuffers::Offset<fbs::BoardSnapshot> root =
      fbs::CreateBoardSnapshotDirect(builder,
                                     &format_version,
                                     &geometry_bytes,
                                     &connectivity_bytes,
                                     &stackup_bytes,
                                     &extensions,
                                     &passthrough_blobs);
  builder.Finish(root);

  const uint8_t* buffer_ptr = builder.GetBufferPointer();
  // GetBufferPointer()/GetSize() are a guaranteed-consistent pair from the
  // FlatBufferBuilder's own contract.
  // NOLINTNEXTLINE(cppcoreguidelines-pro-bounds-pointer-arithmetic)
  return {buffer_ptr, buffer_ptr + builder.GetSize()};
}

BoardSnapshot deserialize_board(std::span<const uint8_t> buffer) {
  // NOLINTNEXTLINE(misc-include-cleaner)
  flatbuffers::Verifier verifier(buffer.data(), buffer.size());
  if (!fbs::VerifyBoardSnapshotBuffer(verifier)) {
    throw FormatError("corrupt or malformed board snapshot buffer");
  }

  const fbs::BoardSnapshot* board = fbs::GetBoardSnapshot(buffer.data());

  // format_version, geometry, connectivity, and stackup are all
  // `(required)` in schemas/snapshot.fbs, so VerifyBoardSnapshotBuffer
  // above already guarantees every pointer dereferenced below is non-null.
  const FormatVersion format_version = read_format_version(board->format_version());
  if (format_version.major != CURRENT_FORMAT_VERSION.major) {
    throw FormatError("unsupported board snapshot format major version");
  }

  BoardSnapshot result;
  result.format_version = format_version;

  const auto* geometry_bytes = board->geometry();
  result.geometry =
      geometry::deserialize_geometry({geometry_bytes->data(), geometry_bytes->size()}).commit();

  const auto* connectivity_bytes = board->connectivity();
  result.connectivity = connectivity::deserialize_connectivity(
                            {connectivity_bytes->data(), connectivity_bytes->size()})
                            .commit();

  const auto* stackup_bytes = board->stackup();
  result.stackup =
      stackup::deserialize_stackup({stackup_bytes->data(), stackup_bytes->size()}).commit();

  if (const auto* extensions = board->extensions()) {
    result.extensions.reserve(extensions->size());
    for (const fbs::ExtensionEntry* entry : *extensions) {
      result.extensions.push_back(read_extension(entry));
    }
  }
  if (const auto* passthrough_blobs = board->passthrough_blobs()) {
    result.passthrough_blobs.reserve(passthrough_blobs->size());
    for (const fbs::PassthroughBlobEntry* entry : *passthrough_blobs) {
      result.passthrough_blobs.push_back(read_passthrough_blob(entry));
    }
  }

  return result;
}

